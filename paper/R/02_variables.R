##################################################################
#####  02_variables.R - 조작적 정의는 «여기 한 곳»에만        #####
##################################################################
##
## Methods 절의 변수 서술은 이 파일을 «열어서» 쓴다. 관례로 그럴듯한 정의를 지어내지
## 않는다 — 랩 규칙(전역 CLAUDE.md「Code Quality Rules」)이 그것을 금지한다.
##
## 이 논문의 변수는 셋뿐이다. 적을수록 좋다.
##   ① 자체충족률   = 관내 / (관내 + 관외), 진료비 기준
##   ② 지역 유형     = 군 / 시 / 구  (지역명 끝 글자로 판정)
##   ③ 총진료량      = 관내 + 관외 (그 지역 «주민»이 받은 진료비 총액)
##
## ⚠ ②는 «행정 위계»이지 도시-농촌 구분이 아니다. 자치구는 대도시 안에 있어 경계를
##    넘기 쉽고, 그래서 자체충족률이 구조적으로 낮다. 층화는 그 «구조»를 보려는 것이지
##    「구가 군보다 나쁘다」를 말하려는 것이 아니다.

add_variables <- function(d) {
  cat("=== 02_variables.R ===\n")

  ## ① 자체충족률 — 부모가 이미 계산해 두었지만 «여기서 다시» 만든다.
  ##    받아 온 열을 그대로 믿으면 정의가 두 곳에 살게 된다. 대신 대조해서 어긋나면 멈춘다.
  d$총진료량 <- d$관내 + d$관외
  d$자체충족 <- 100 * d$관내 / d$총진료량
  if (!is.null(d$자체충족률)) {
    gap <- max(abs(d$자체충족 - d$자체충족률), na.rm = TRUE)
    if (gap > 1e-6)
      stop("02_variables: 자체충족률이 부모 값과 어긋난다(최대 ", gap, ")")
    cat("--- 자체충족률 재계산이 부모 값과 일치(최대 오차 0)\n")
  }

  ## ② 지역 유형 — 지역명의 «끝 글자». 「수원시장안구」처럼 시 안의 구도 구로 잡힌다.
  ##    그것이 의도다: 경계를 넘기 쉬운 단위인가가 기준이지 상위 행정구역이 아니다.
  last <- substr(d$지역, nchar(d$지역), nchar(d$지역))
  d$유형 <- ifelse(last == "군", "군", ifelse(last == "구", "구",
                   ifelse(last == "시", "시", "기타")))
  if (any(d$유형 == "기타")) {
    odd <- unique(d$지역[d$유형 == "기타"])
    cat("--- ⚠ 유형 미분류", length(odd), "곳:", paste(utils::head(odd, 8), collapse = ", "), "\n")
  }

  ## ③ 기준연도 대비 지수 — 「같은 곳의 변화」를 보려면 수준이 아니라 지수여야 한다.
  y0 <- min(d$연도)
  base <- d[d$연도 == y0, c("sgg", "관내", "관외", "총진료량", "자체충족")]
  names(base)[-1] <- paste0("기준_", names(base)[-1])
  d <- merge(d, base, by = "sgg", all.x = TRUE)
  d$지수_관내 <- 100 * d$관내 / d$기준_관내
  d$지수_관외 <- 100 * d$관외 / d$기준_관외
  d$변화_자체충족 <- d$자체충족 - d$기준_자체충족

  d <- d[order(d$sgg, d$연도), ]
  cat(sprintf("--- 변수 %d개 시군구 × %d년, 기준연도 %d\n",
              length(unique(d$sgg)), length(unique(d$연도)), y0))
  d
}
